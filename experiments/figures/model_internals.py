r"""Look inside a trained model: separated spectrograms, latent states, prior samples, features.

Reproduces the qualitative model figures of the dissertation for one mixture file:
the separated source spectrograms, the latent state trajectories of each source, spectrograms
generated by sampling the dynamical prior, and feature maps of the encoder and decoder.

    python experiments/figures/model_internals.py --model runs/k5/model.pt \\
        --audio examples/mixture.wav --out figures/internals
"""

from __future__ import annotations

import argparse
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import torch

from dvae_bss import load_model
from dvae_bss.data import read_audio

GREYS = dict(aspect="auto", origin="lower", interpolation="none", cmap="Greys")


def log_spectrogram(magnitude: torch.Tensor, floor: float = 1e-4) -> np.ndarray:
    """Natural log of compressed magnitudes, clipped below ``floor``."""
    return magnitude.clamp_min(floor).log().numpy()


def row_of_images(images: list[np.ndarray], filename: Path, titles=None, **kwargs) -> None:
    """Images side by side with shared axes."""
    fig, axes = plt.subplots(
        1, len(images), figsize=(1.6 * len(images) + 0.4, 2), sharey=True, squeeze=False
    )
    for k, (ax, image) in enumerate(zip(axes[0], images, strict=True)):
        ax.imshow(image, **GREYS, **kwargs)
        ax.set_xlabel("time")
        if titles:
            ax.set_title(titles[k], fontsize="small")
    axes[0, 0].set_ylabel("frequency")
    fig.tight_layout()
    fig.savefig(filename, bbox_inches="tight")
    plt.close(fig)


def feature_maps(
    network: torch.nn.Sequential, x: torch.Tensor, filename: Path, channels: int = 12
) -> None:
    """Grid of feature maps after each layer of ``network`` (``<filename>_<layer>.png``)."""
    with torch.no_grad():
        for layer, module in enumerate(network, start=1):
            x = module(x)
            maps = x[0].clone()
            maps = (maps - maps.min()) / (maps.max() - maps.min() + 1e-12)
            n = min(channels, maps.shape[0])
            fig, axes = plt.subplots(4, 3, figsize=(3, 2.8), squeeze=False)
            for ax in axes.ravel():
                ax.axis("off")
            for ax, feature in zip(axes.ravel()[:n], maps[:n], strict=False):
                ax.imshow(feature, interpolation="none", origin="lower", cmap="Greys")
            fig.subplots_adjust(wspace=0.05, hspace=0.05)
            fig.savefig(filename.with_name(f"{filename.name}_{layer}.png"), dpi=150)
            plt.close(fig)


def main(argv: list[str] | None = None) -> None:
    """Write the figures."""
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("-m", "--model", type=Path, required=True)
    parser.add_argument("--legacy-config", type=Path)
    parser.add_argument("--audio", type=Path, required=True, help="mixture to analyse")
    parser.add_argument("-o", "--out", type=Path, default=Path("figures/internals"))
    parser.add_argument("--samples", type=int, default=3, help="prior samples to draw")
    parser.add_argument("--seed", type=int, default=2)
    args = parser.parse_args(argv)
    torch.manual_seed(args.seed)
    args.out.mkdir(parents=True, exist_ok=True)

    model, stft = load_model(args.model, args.legacy_config)
    model.eval()
    wave = read_audio(args.audio, stft.sample_rate).unsqueeze(0)
    x = stft.magnitude(wave)
    with torch.no_grad():
        output = model(x, stochastic=False)
        samples, _ = model.sample(n_steps=output["mu_q"].shape[1], n_samples=args.samples)

    ranges = dict(vmin=-8)
    row_of_images([log_spectrogram(x[0])], args.out / "mixture.pdf", **ranges)
    row_of_images(
        [log_spectrogram(output["recon_x"][0])], args.out / "mixture_estimate.pdf", **ranges
    )
    sources = [log_spectrogram(s) for s in output["recon_s"][0]]
    row_of_images(
        sources,
        args.out / "sources.pdf",
        [f"source {k + 1}" for k in range(len(sources))],
        **ranges,
    )
    states = [z.abs().T.numpy() for z in output["z"]]
    row_of_images(
        states, args.out / "latent_states.pdf", [f"source {k + 1}" for k in range(len(states))]
    )
    for j, sample in enumerate(samples, start=1):
        row_of_images(
            [log_spectrogram(s) for s in sample], args.out / f"prior_sample_{j}.pdf", **ranges
        )
    feature_maps(model.Encoder.Network, x.unsqueeze(1), args.out / "encoder_features")
    decoder_input = model.fc_decoder(output["z"].transpose(-2, -1))
    decoder_input = decoder_input.reshape(
        decoder_input.shape[0], model.conv_channels, -1, decoder_input.shape[-1]
    )
    feature_maps(model.Decoder.Network, decoder_input[:1], args.out / "decoder_features")
    print(args.out)


if __name__ == "__main__":
    main()
